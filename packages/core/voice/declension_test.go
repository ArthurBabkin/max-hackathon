package voice

import "testing"

// Кейсы перенесены один в один из apps/web/src/lib/declension.test.ts:
// бот и мини-приложение должны склонять имя одинаково.

func TestGenitive(t *testing.T) {
	cases := []struct{ name, want string }{
		// мужские на согласную
		{"Артём", "Артёма"},
		{"Иван", "Ивана"},
		{"Александр", "Александра"},
		{"Тимур", "Тимура"},
		// мужские на -й
		{"Алексей", "Алексея"},
		{"Андрей", "Андрея"},
		{"Николай", "Николая"},
		// мужские на -ь
		{"Игорь", "Игоря"},
		{"Даниэль", "Даниэля"},
		// на -а и -я склоняются одинаково независимо от пола
		{"Ольга", "Ольги"},
		{"Анна", "Анны"},
		{"Маша", "Маши"},
		{"Лика", "Лики"},
		{"Никита", "Никиты"},
		{"Илья", "Ильи"},
		{"Катя", "Кати"},
		{"Настя", "Насти"},
		// -ия
		{"Мария", "Марии"},
		{"Наталия", "Наталии"},
		{"Ксения", "Ксении"},
		// беглая гласная
		{"Павел", "Павла"},
		{"Лев", "Льва"},
		{"Пётр", "Петра"},
		// несклоняемые
		{"Отто", "Отто"},
		{"Мэри", "Мэри"},
		{"Нино", "Нино"},
		{"Alex", "Alex"},
		{"Jane", "Jane"},
		// Любовь склоняется не как Игорь
		{"Любовь", "Любови"},
		// пустое имя не ломает подстановку
		{"", ""},
		// лишние пробелы обрезаются
		{"  Артём  ", "Артёма"},
		// регистр имени сохраняется
		{"АРТЁМ", "АРТЁМа"},
	}
	for _, c := range cases {
		if got := Genitive(c.name); got != c.want {
			t.Errorf("Genitive(%q) = %q, ждали %q", c.name, got, c.want)
		}
	}
}

