package names

import "testing"

func TestOlympiad(t *testing.T) {
	for in, want := range map[string]string{
		"Всероссийская олимпиада школьников «Высшая проба»":                                       "Высшая проба",
		"Олимпиада школьников по программированию «ТехноКубок»":                                   "ТехноКубок",
		"«Формула Единства»/«Третье тысячелетие»":                                                 "Формула Единства",
		"Олимпиада школьников Санкт-Петербургского государственного университета":                 "Олимпиада СПбГУ",
		"Открытая региональная межвузовская олимпиада школьников (ОРМО) с международным участием": "ОРМО",
		"ВсОШ по информатике":             "ВсОШ по информатике",
		"Турнир городов":                  "Турнир городов",
		"Олимпиада без закрытой «кавычки": "Олимпиада без закрытой «кавычки",
		"": "",
	} {
		if got := Olympiad(in); got != want {
			t.Errorf("Olympiad(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestKey(t *testing.T) {
	if Key("Ёлка") != Key("елка") || !(Key("Высшая проба") < Key("ТехноКубок")) {
		t.Fatal("ключ сортировки без регистра и с «ё» как «е»")
	}
}
