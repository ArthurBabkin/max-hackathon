// Package names — как олимпиады называются в интерфейсе. В базе лежит
// официальное название из перечня: по нему ищет помощник и сверяется
// контент. В списках, карточках и сообщениях нужно короткое и узнаваемое —
// «Высшая проба», а не «Всероссийская олимпиада школьников «Высшая проба»».
package names

import "strings"

// short — сокращения для длинных названий без кавычек. Только те, что
// есть в самом названии или общеприняты для вуза-организатора.
var short = map[string]string{
	"Олимпиада школьников Санкт-Петербургского государственного университета":                                                   "Олимпиада СПбГУ",
	"Олимпиада школьников Российской академии народного хозяйства и государственной службы при Президенте Российской Федерации": "Олимпиада РАНХиГС",
	"Межрегиональные предметные олимпиады Казанского (Приволжского) федерального университета":                                  "Олимпиады КФУ",
	"Открытая региональная межвузовская олимпиада школьников (ОРМО) с международным участием":                                   "ОРМО",
	"Всероссийская междисциплинарная олимпиада школьников «Национальная технологическая олимпиада»":                             "НТО",
}

// Olympiad — название для интерфейса: первое название в кавычках
// («Формула Единства»/«Третье тысячелетие» — это «Формула Единства»); без
// кавычек — сокращение из словаря или официальное название как есть.
func Olympiad(name string) string {
	if s, ok := short[name]; ok {
		return s
	}
	open := strings.Index(name, "«")
	if open < 0 {
		return name
	}
	rest := name[open+len("«"):]
	if end := strings.Index(rest, "»"); end > 0 {
		return rest[:end]
	}
	return name
}

// Key — ключ сортировки по алфавиту: без регистра, «ё» как «е».
func Key(name string) string {
	return strings.ReplaceAll(strings.ToLower(name), "ё", "е")
}
