import { describe, expect, it } from 'vitest'
import { dative, genitive } from './declension'

/**
 * Из MAX приходит только именительный падеж имени, а ТЗ F3 требует
 * «Цель Артёма» и «Предложить Артёму». Склонять приходится на нашей стороне.
 */
describe('genitive — кого? чего?', () => {
  it.each([
    // мужские на согласную
    ['Артём', 'Артёма'],
    ['Иван', 'Ивана'],
    ['Александр', 'Александра'],
    ['Тимур', 'Тимура'],
    // мужские на -й
    ['Алексей', 'Алексея'],
    ['Андрей', 'Андрея'],
    ['Николай', 'Николая'],
    // мужские на -ь
    ['Игорь', 'Игоря'],
    ['Даниэль', 'Даниэля'],
    // на -а и -я склоняются одинаково независимо от пола
    ['Ольга', 'Ольги'],
    ['Анна', 'Анны'],
    ['Маша', 'Маши'],
    ['Лика', 'Лики'],
    ['Никита', 'Никиты'],
    ['Илья', 'Ильи'],
    ['Катя', 'Кати'],
    ['Настя', 'Насти'],
    // -ия
    ['Мария', 'Марии'],
    ['Наталия', 'Наталии'],
    ['Ксения', 'Ксении'],
  ])('%s → %s', (имя, ожидаем) => {
    expect(genitive(имя)).toBe(ожидаем)
  })

  describe('беглая гласная', () => {
    it.each([
      ['Павел', 'Павла'],
      ['Лев', 'Льва'],
      ['Пётр', 'Петра'],
    ])('%s → %s', (имя, ожидаем) => {
      expect(genitive(имя)).toBe(ожидаем)
    })
  })

  describe('несклоняемые', () => {
    it.each([
      ['Отто', 'Отто'],
      ['Мэри', 'Мэри'],
      ['Нино', 'Нино'],
      ['Alex', 'Alex'],
      ['Jane', 'Jane'],
    ])('%s не меняется', (имя, ожидаем) => {
      expect(genitive(имя)).toBe(ожидаем)
    })
  })

  describe('пограничные случаи', () => {
    it('Любовь склоняется не как Игорь', () => {
      expect(genitive('Любовь')).toBe('Любови')
    })

    it('пустое имя не ломает подстановку', () => {
      expect(genitive('')).toBe('')
    })

    it('лишние пробелы обрезаются', () => {
      expect(genitive('  Артём  ')).toBe('Артёма')
    })

    it('регистр имени сохраняется', () => {
      expect(genitive('АРТЁМ')).toBe('АРТЁМа')
    })
  })
})

describe('dative — кому? чему?', () => {
  it.each([
    ['Артём', 'Артёму'],
    ['Иван', 'Ивану'],
    ['Алексей', 'Алексею'],
    ['Игорь', 'Игорю'],
    ['Ольга', 'Ольге'],
    ['Анна', 'Анне'],
    ['Никита', 'Никите'],
    ['Илья', 'Илье'],
    ['Катя', 'Кате'],
    ['Мария', 'Марии'],
    ['Павел', 'Павлу'],
    ['Лев', 'Льву'],
    ['Любовь', 'Любови'],
    ['Отто', 'Отто'],
    ['Alex', 'Alex'],
  ])('%s → %s', (имя, ожидаем) => {
    expect(dative(имя)).toBe(ожидаем)
  })
})
