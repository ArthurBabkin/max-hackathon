package api

import "testing"

// «100 баллов» — с предметом, по которому их засчитают: сид пишет его в
// примечание, подпись льготы говорит его сразу.
func TestBenefitLabel(t *testing.T) {
	inf := ptr("Подтвердить ЕГЭ: Информатика. 100 баллов засчитают по предмету «Информатика»")
	either := ptr("100 баллов засчитают по предмету «Информатика» или «Математика»")
	unknown := ptr("Предмет, по которому засчитают 100 баллов, уточните в приёмной комиссии")
	for _, tc := range []struct {
		name  string
		kind  string
		notes []*string
		want  string
	}{
		{"предмет", "score100", []*string{inf}, "100 баллов по информатике"},
		{"варианты", "score100", []*string{either}, "100 баллов по информатике или математике"},
		{"предмет неизвестен", "score100", []*string{unknown}, "100 баллов"},
		{"без примечания", "score100", []*string{nil}, "100 баллов"},
		{"у вузов один предмет", "score100", []*string{inf, inf}, "100 баллов по информатике"},
		{"у вузов разные", "score100", []*string{inf, either}, "100 баллов"},
		{"предмета нет в словаре", "score100", []*string{ptr("100 баллов засчитают по предмету «Черчение»")}, "100 баллов"},
		{"не 100 баллов", "bvi", []*string{inf}, "БВИ"},
	} {
		if got := benefitLabel(tc.kind, tc.notes...); got != tc.want {
			t.Errorf("%s: %q, ждали %q", tc.name, got, tc.want)
		}
	}
}
