"""Датасет A: разбор таблиц приложений ВШЭ по кампусам и отсев филиалов."""
import unittest
from unittest import mock

import build_a as ba


def page(n, *rows):
    return {"page": n, "text": "", "tables": [list(rows)]}


def head(code, name):
    return ["", f"Направление подготовки {code} {name}", "", "", "", ""]


class HseRowsTest(unittest.TestCase):
    def test_program_row(self):
        rows = ba.hse_rows([page(1, head("09.03.04", "Программная инженерия"),
                                 ["1", "", "Разработка информационных систем для бизнеса", "", "", "математика"],
                                 ["", "", "", "", "", "русский язык"])])
        self.assertEqual(rows, [("09.03.04", "Программная инженерия",
                                 "Разработка информационных систем для бизнеса", 1)])

    def test_name_carried_over_to_next_page(self):
        # Пермь, 38.03.05: у строки с номером название уехало на следующую
        # страницу, а первая ячейка с текстом — предмет ВИ «математика».
        rows = ba.hse_rows([
            page(2, head("38.03.05", "Бизнес-информатика"),
                 ["7", "", "", "", "", "математика", "алгебра и начала анализа"]),
            page(3, ["", "", "Разработка информационных систем для бизнеса", "", "", "информатика"],
                 ["", "", "", "", "", "русский язык"],
                 head("40.03.01", "Юриспруденция"),
                 ["8", "", "Юриспруденция", "", "", "обществознание"]),
        ])
        self.assertEqual(rows, [
            ("38.03.05", "Бизнес-информатика", "Разработка информационных систем для бизнеса", 2),
            ("40.03.01", "Юриспруденция", "Юриспруденция", 3),
        ])

    def test_part_time_section_is_not_read(self):
        # Очно-заочные программы — только платные места и приём после
        # колледжа: олимпиадных льгот у них нет, в датасет они не идут.
        rows = ba.hse_rows([page(5, head("54.03.01", "Дизайн"),
                                 ["14", "", "Дизайн", "", "", "творческое испытание"],
                                 ["ОЧНО-ЗАОЧНАЯ ФОРМА ОБУЧЕНИЯ", "", "", "", "", ""],
                                 head("09.03.04", "Программная инженерия"),
                                 ["1", "", "Программная инженерия", "", "+", "Профессиональ ный экзамен"])])
        self.assertEqual([r[2] for r in rows], ["Дизайн"])


def parsed(parser, *pages):
    """Программы парсера вуза на подставленных страницах документа."""
    with mock.patch.object(ba, "load_pages", return_value=list(pages)), \
         mock.patch.object(ba, "_src", lambda vuz, f, page: {"source_url": "u", "source_page": page}):
        return [(p["faculty"], p["program_name"]) for p in parser()]


class BranchesTest(unittest.TestCase):
    """Филиал — отдельный вуз со своим приёмом: его программы и льготы
    не должны выдаваться за программы головного вуза."""

    def test_hse_moscow_only(self):
        self.assertEqual(set(ba.HSE_CAMPUS.values()), {"Москва"})

    def test_msu_branch_sections_skipped(self):
        # kcp_bak.pdf: секции «Филиал МГУ в г. Грозном» и «… в г. Севастополе».
        blank = ["", "", "", ""]
        got = parsed(ba.parse_msu, page(
            2, ["Факультет вычислительной математики и кибернетики", *blank],
            ["01.03.02", "Прикладная математика и информатика", "312", "50", "ЕГЭ"],
            ["Филиал МГУ в г. Севастополе", *blank],
            ["01.03.02", "Прикладная математика и информатика", "20", "5", "ЕГЭ"],
            ["Экономический факультет", *blank],
            ["38.03.01", "Экономика", "100", "80", "ЕГЭ"]))
        self.assertEqual(got, [
            ("Факультет вычислительной математики и кибернетики", "Прикладная математика и информатика"),
            ("Экономический факультет", "Экономика"),
        ])

    def test_kfu_faculty_is_section_and_branches_skipped(self):
        # План приёма, стр. 10–16: Елабужский институт (филиал), Набережночелнинский
        # институт (в шапке без слова «филиал», но с названием юрлица) и Джизак.
        def head(name):
            return [name] + [""] * 20

        def prog(code, name):
            return [code, name, name, "бакалавриат", "09.00.00 Информатика", *[""] * 9, "25", *[""] * 6]

        got = parsed(ba.parse_kfu, page(
            10, head("Институт физики"), prog("03.03.02", "Физика"),
            head('Елабужский институт (филиал) ФГАОУ ВО "Казанский (Приволжский) федеральный университет"'),
            prog("44.03.05", "Математика и информатика"),
            head('Набережночелнинский институт ФГАОУ ВО "Казанский (Приволжский) федеральный университет"'),
            prog("09.03.04", "Разработка программно-информационных систем"),
            head("Филиал КФУ в городе Джизаке"), prog("38.03.01", "Экономика")))
        self.assertEqual(got, [("Институт физики", "Физика")])

    def test_sechenov_branch_pages_and_foreign_groups_skipped(self):
        # Приложение 1: стр. 3 — Бакинский филиал, стр. 4 — Брянский; конкурсные
        # группы для иностранных граждан — не для школьников из России.
        def pg(n, text, *rows):
            return {"page": n, "text": text, "tables": [list(rows)]}

        got = parsed(ba.parse_sechenov,
                     pg(2, "Перечень специальностей", ["31.05.01", "Лечебное дело"],
                        ["31.05.01", "Лечебное дело (Конкурсная группа для иностранных граждан)"]),
                     pg(3, "по которым будет проводиться прием в Бакинский филиал ФГАОУ ВО",
                        ["31.05.03", "Стоматология"]))
        self.assertEqual(got, [("Сеченовский Университет", "Лечебное дело")])


if __name__ == "__main__":
    unittest.main()
