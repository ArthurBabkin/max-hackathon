#!/usr/bin/env python3
"""Программа вуза -> profile_group из справочника 1.2.

Ключ матчинга — смысл программы, а не код ОКСО (п. 1.2 спеки: у Иннополиса
нет ни 01.03.02, ни 09.03.04, и это не повод писать not_offered).
Поэтому у каждого попадания есть match_type:
  exact    — код входит в ядро группы либо название прямо называет предмет группы;
  adjacent — смежная область, засчитываем по решению заказчика, но помечаем.
"""
import re

# Коды ОКСО, однозначно принадлежащие группе.
EXACT_CODES = {
    "ИТ": {"01.03.02", "02.03.01", "02.03.02", "02.03.03",
           "09.03.01", "09.03.02", "09.03.03", "09.03.04", "10.03.01", "09.05.01"},
    "Физика": {"03.03.01", "03.03.02", "03.05.01", "14.03.02", "16.03.01"},
    "Биомед": {"31.05.01", "31.05.02", "31.05.03", "30.05.01", "30.05.02", "30.05.03",
               "32.05.01", "33.05.01", "06.03.01", "06.05.01", "34.03.01"},
    "Экономика": {"38.03.01", "38.05.01"},
}

# Смежные коды: засчитываем как offered, но с match_type=adjacent.
ADJACENT_CODES = {
    "ИТ": {"01.03.01", "01.03.04", "11.03.02", "12.03.04", "15.03.06", "27.03.04",
           "38.03.05", "09.03.00", "15.03.04"},
    "Физика": {"11.03.04", "12.03.03", "12.03.05", "28.03.03", "22.03.01", "03.03.03"},
    "Биомед": {"19.03.01", "12.03.04", "36.05.01", "33.05.02"},
    "Экономика": {"38.03.02", "38.03.03", "38.03.04", "38.03.06", "27.03.05", "38.03.07"},
}

# Ключевые слова в названии программы — работают, когда код нестандартный.
EXACT_WORDS = {
    "ИТ": [r"\bинформатик", r"программн\w+ инженери", r"программировани",
           r"вычислительн\w+ техник", r"компьютерн\w+ наук", r"прикладная математика и информатик",
           r"software", r"computer science"],
    "Физика": [r"\bфизик", r"прикладные математика и физика", r"физтех"],
    "Биомед": [r"лечебн\w+ дел", r"\bбиологи", r"педиатри", r"медицинск\w+ биохими",
               r"фундаментальн\w+ медицин", r"стоматологи", r"фармаци", r"биоинформатик"],
    "Экономика": [r"\bэкономик"],
}

ADJACENT_WORDS = {
    "ИТ": [r"искусственн\w+ интеллект", r"\bданны[хе]\b", r"робототехник",
           r"информационн\w+ систем", r"информационн\w+ безопасност", r"бизнес-информатик",
           r"математическое моделировани", r"мехатроник"],
    "Физика": [r"биофизик", r"фотоник", r"наноматериал", r"материаловедени",
               r"техническая физика", r"ядерн"],
    "Биомед": [r"биотехнолог", r"биоинженери", r"биотехническ", r"медицинск",
               r"нейротехнолог", r"сестринск"],
    "Экономика": [r"менеджмент", r"финанс", r"инноватик", r"бизнес", r"государственн\w+ и муниципальн\w+ управлени"],
}

GROUPS = ("ИТ", "Физика", "Биомед", "Экономика")


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "")).replace("­", "").strip().lower()


def classify(program_name: str, napravlenie_code: str = "", napravlenie_name: str = "") -> list[dict]:
    """-> [{profile_group, match_type, matched_reason}], возможно несколько групп."""
    code = (napravlenie_code or "").strip()[:8]
    haystack = f"{_norm(program_name)} {_norm(napravlenie_name)}"
    hits = []

    for group in GROUPS:
        if code in EXACT_CODES[group]:
            hits.append({"profile_group": group, "match_type": "exact",
                         "matched_reason": f"код {code} входит в ядро группы"})
            continue
        owned_elsewhere = any(code in EXACT_CODES[g] for g in GROUPS if g != group)
        word = next((w for w in EXACT_WORDS[group] if re.search(w, haystack)), None)
        if word and not owned_elsewhere:
            hits.append({"profile_group": group, "match_type": "exact",
                         "matched_reason": f"название прямо называет предмет группы (/{word}/)"})
            continue
        if code in ADJACENT_CODES[group]:
            hits.append({"profile_group": group, "match_type": "adjacent",
                         "matched_reason": f"код {code} — смежная область, точного кода группы у вуза нет"})
            continue
        word = next((w for w in ADJACENT_WORDS[group] if re.search(w, haystack)), None)
        if word:
            hits.append({"profile_group": group, "match_type": "adjacent",
                         "matched_reason": f"смежное по названию (/{word}/)"})
    return hits


def demo() -> None:
    """Проверка на реальных программах из скоупа, включая спорные решения заказчика."""
    def g(*a):
        return {(h["profile_group"], h["match_type"]) for h in classify(*a)}

    # точные попадания
    assert ("ИТ", "exact") in g("Прикладная математика и информатика", "01.03.02")
    assert ("Физика", "exact") in g("Фундаментальная и экспериментальная физика", "03.03.02")
    assert ("Биомед", "exact") in g("Лечебное дело", "31.05.01")
    assert ("Экономика", "exact") in g("Экономика", "38.03.01")
    # Иннополис: код вне ядра ИТ, но смысл тот же (прямой пример из п.1.2 спеки)
    assert ("ИТ", "exact") in g("Информатика и вычислительная техника", "09.03.01")
    # смежные решения, утверждённые заказчиком
    assert ("Экономика", "adjacent") in g("Менеджмент", "38.03.02"), "Сеченов: менеджмент вместо экономики"
    assert ("Экономика", "adjacent") in g("Бизнес-информатика", "38.03.05"), "ИТМО: бизнес-информатика"
    assert ("Биомед", "adjacent") in g("Биотехнология", "19.03.01"), "МФТИ: биотех вместо биомеда"
    assert ("Физика", "adjacent") in g("Медицинская биофизика", "30.05.02"), "Сеченов: медбиофизика"
    # медбиофизика остаётся и Биомедом — у неё код из ядра биомеда
    assert ("Биомед", "exact") in g("Медицинская биофизика", "30.05.02")
    # не должно цеплять лишнее
    assert not g("История", "46.03.01")
    # ловушки, найденные на реальных данных МГУ
    assert ("Экономика", "exact") not in g('Юриспруденция (финансово-правовой профиль)', "40.03.01")
    assert not g("Публичная политика и социальные науки", "41.03.06")
    assert ("Экономика", "adjacent") in g("Государственное и муниципальное управление", "38.03.04")
    # «оптоинформатика» — это фотоника, а не информатика (ложное срабатывание у ИТМО)
    assert ("ИТ", "exact") not in g("Физика наноструктур", "12.03.03", "Фотоника и оптоинформатика")
    assert ("Физика", "exact") in g("Физика наноструктур", "12.03.03", "Фотоника и оптоинформатика")
    assert not g("Юриспруденция", "40.03.01")
    print("classify: все проверки прошли")


if __name__ == "__main__":
    demo()
